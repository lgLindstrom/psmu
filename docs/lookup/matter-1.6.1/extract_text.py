#!/usr/bin/env python3
"""Extract searchable text from the Matter specification PDFs.

Produces one .txt file per PDF in ./text. Every page starts with a marker that
names both the PDF page (1-based, as used by PDF readers) and the printed page
number from the document footer. Tables are kept as markdown rows, one row per
line, so that grepping for an attribute ID or a cluster name returns the whole
row instead of a single table cell.

The PDFs and the generated text are not redistributed; see the licence note in
INDEX.md. This script is not part of the firmware build.

Requires pymupdf and pymupdf4llm (pip install pymupdf pymupdf4llm).

Usage:
    python3 extract_text.py            # all PDFs in this directory
    python3 extract_text.py foo.pdf    # selected files
"""

import re
import sys
from pathlib import Path

import pymupdf
import pymupdf4llm


def normalise(markdown):
    """Turn one page of markdown into plain, greppable text.

    pymupdf4llm marks up headings and table cells with "**", wraps table cells
    with "<br>", and keeps the PDF's soft hyphens at line breaks. Joining a
    soft hyphen with the following break restores whole words such as
    "RemainingDuration", which would otherwise be impossible to grep.
    """
    text = markdown.replace("**", "")
    text = text.replace("\u00ad<br>", "")
    text = text.replace("\u00ad\n", "")
    text = text.replace("\u00ad", "")
    text = text.replace("<br>", " ")
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def printed_page_number(text):
    """Return the page number printed in the footer, or None."""
    match = re.search(r"\bPage\s+(\d+)\b", text)
    return match.group(1) if match else None


def extract(pdf_path, out_path):
    doc = pymupdf.open(pdf_path)
    pages = list(range(doc.page_count))
    chunks = pymupdf4llm.to_markdown(
        str(pdf_path), pages=pages, page_chunks=True, show_progress=False
    )
    if len(chunks) != len(pages):
        raise RuntimeError(
            f"{pdf_path.name}: expected {len(pages)} chunks, got {len(chunks)}"
        )
    with out_path.open("w", encoding="utf-8") as out:
        out.write(f"# Extracted text: {pdf_path.name}\n")
        out.write(f"# Pages: {doc.page_count}. Generated by extract_text.py.\n")
        out.write("# Table rows are kept on one line. Verify tables in the PDF.\n\n")
        for page_index, chunk in enumerate(chunks):
            text = normalise(chunk["text"])
            printed = printed_page_number(text)
            marker = f"===== PDF page {page_index + 1}"
            if printed:
                marker += f" / printed page {printed}"
            out.write(marker + " =====\n")
            out.write(text)
            out.write("\n\n")
    print(f"{pdf_path.name}: {doc.page_count} pages -> {out_path}")


def main(argv):
    here = Path(__file__).resolve().parent
    out_dir = here / "text"
    out_dir.mkdir(exist_ok=True)
    if argv:
        pdfs = [Path(arg).resolve() for arg in argv]
    else:
        pdfs = sorted(here.glob("*.pdf"))
    for pdf in pdfs:
        extract(pdf, out_dir / (pdf.stem + ".txt"))


if __name__ == "__main__":
    main(sys.argv[1:])
